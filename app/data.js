// verdict: how strong the cut is, computed from the two prices alone.
export function discountPct(d) {
  return Math.round((1 - d.sale / d.was) * 100);
}

export function verdict(d) {
  const p = discountPct(d);
  if (p >= 50) return { label: 'Deep cut', cls: 'deep' };
  if (p >= 40) return { label: 'Big saving', cls: 'big' };
  if (p >= 20) return { label: 'Solid deal', cls: 'solid' };
  return { label: 'Modest cut', cls: 'modest' };
}

